function setLanguage(lang) {
  document.documentElement.lang = lang;

  localStorage.setItem("language", lang);

  // Translate normal elements using data-i18n
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const keys = element.dataset.i18n.split(".");

    let value = translations[lang];

    keys.forEach(key => {
      value = value?.[key];
    });

    if (value !== undefined) {
      element.innerHTML = value;
    }

    // Special case for email links
    if (
      element.tagName === "A" &&
      element.dataset.i18n === "contacto.email"
    ) {
      element.href = `mailto:${value}`;
    }
  });

  // Translate placeholders using data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const keys = element.dataset.i18nPlaceholder.split(".");

    let value = translations[lang];

    keys.forEach(key => {
      value = value?.[key];
    });

    if (value !== undefined) {
      element.placeholder = value;
    }
  });

  const menuPdfButton = document.getElementById("about-menu-button");

  if (menuPdfButton) {
    menuPdfButton.href =
      lang === "es"
        ? "Fuego_Brasa_Menu_Spanish.pdf"
        : "Fuego_Brasa_Menu_English.pdf";
    menuPdfButton.setAttribute(
      "aria-label",
      lang === "es" ? "Ver menú" : "View menu"
    );
  }

  // Update page title
  document.title =
    lang === "es"
      ? "Brasaland — Restaurante en Colombia y Florida"
      : "Brasaland — Grill Restaurant in Colombia and Florida";

  // Update meta description
  const metaDescription = document.querySelector(
    'meta[name="description"]'
  );

  if (metaDescription) {
    metaDescription.setAttribute(
      "content",
      lang === "es"
        ? "Brasaland: cocina de temporada..."
        : "Brasaland: seasonal cuisine..."
    );
  }

  document.dispatchEvent(new Event("languagechange"));
}

